vbsme:  
    li      $v0, 0              # reset $v0 and $V1
    li      $v1, 0

    addi $sp, $sp, -32
    sw   $ra, 28($sp)
    sw   $s0, 24($sp)   # bestSAD
    sw   $s1, 20($sp)   # bestX
    sw   $s2, 16($sp)   # bestY
    sw   $s3, 12($sp)   # diag
    sw   $s4, 8($sp)    # i
    sw   $s5, 4($sp)    # n
    sw   $s6, 0($sp)    # m

    # Load sizes from asize array
    lw   $s7, 0($a0)    # I
    lw   $t0, 4($a0)    # J
    lw   $t1, 8($a0)    # K
    lw   $t2, 12($a0)   # L

    li   $s0, 0x7fffffff   # bestSAD
    li   $s1, 0             # bestX
    li   $s2, 0             # bestY

    # diag = 0 to (I-K)+(J-L)
    li   $s3, 0
    sub  $t3, $s7, $t1      # I-K
    sub  $t4, $t0, $t2      # J-L
    add  $t5, $t3, $t4      # max diag

diag_loop:
    bgt  $s3, $t5, end_diag

    andi $t6, $s3, 1        # diag % 2

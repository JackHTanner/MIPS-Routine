    addi $sp, $sp, -32
    sw   $ra, 28($sp)
    sw   $s0, 24($sp)   # sum
    sw   $s1, 20($sp)   # row loop
    sw   $s2, 16($sp)   # col loop
    sw   $s3, 12($sp)   # I
    sw   $s4, 8($sp)    # J
    sw   $s5, 4($sp)    # K
    sw   $s6, 0($sp)    # L

    # Load I,J,K,L from caller's stack
    lw   $s3, 0($sp)    # I
    lw   $s4, 4($sp)    # J
    lw   $s5, 8($sp)    # K
    lw   $s6, 12($sp)   # L

    li   $s0, 0         # sum = 0

    # Outer loop over rows s = n .. n+K-1
    move $s1, $zero
row_loop:
    bge  $s1, $s5, end_row_loop
    # Outer row index in window: s = n + s1
    add  $t0, $a2, $s1  # t0 = s

    # Inner loop over columns d = m .. m+L-1
    move $s2, $zero
col_loop:
    bge  $s2, $s6, end_col_loop
    add  $t1, $a3, $s2  # d = m + s2

    # Compute offsets
    # offsetV = s*J + d
    mul  $t2, $t0, $s4
    add  $t2, $t2, $t1
    sll  $t2, $t2, 2      # word offset
    add  $t3, $a0, $t2    # addr V[s][d]
    lw   $t4, 0($t3)

    # offsetB = s1*L + s2
    mul  $t5, $s1, $s6
    add  $t5, $t5, $s2
    sll  $t5, $t5, 2
    add  $t6, $a1, $t5
    lw   $t7, 0($t6)

    # sum += abs(V[s][d] - B[s1][s2])
    sub  $t8, $t4, $t7
    bltz $t8, neg_val
    add  $s0, $s0, $t8
    j end_abs
neg_val:
    sub  $t8, $zero, $t8
    add  $s0, $s0, $t8
end_abs:

    addi $s2, $s2, 1
    j col_loop
end_col_loop:
    addi $s1, $s1, 1
    j row_loop
end_row_loop:

    move $v0, $s0  # return sum

    lw   $ra, 28($sp)
    lw   $s0, 24($sp)
    lw   $s1, 20($sp)
    lw   $s2, 16($sp)
    lw   $s3, 12($sp)
    lw   $s4, 8($sp)
    lw   $s5, 4($sp)
    lw   $s6, 0($sp)
    addi $sp, $sp, 32
    jr   $ra

    beq  $t8, $zero, skip_odd
    move $s0, $t7
    move $s1, $s5
    move $s2, $s6
skip_odd:
    addi $s4, $s4, -1
    j odd_i_loop
end_odd_i:

    j diag_done

even_diag:
    li   $s4, 0
even_i_loop:
    bgt  $s4, $s3, end_even_i
    move $s5, $s4       # n = i
    sub  $s6, $s3, $s4  # m = diag-i
    ble  $s5, $t3, call_sad_even
    j skip_even
call_sad_even:
    move $a2, $s5
    move $a3, $s6
    addi $sp, $sp, -16
    sw   $s7, 0($sp)
    sw   $t0, 4($sp)
    sw   $t1, 8($sp)
    sw   $t2, 12($sp)
    jal  computeSAD
    addi $sp, $sp, 16
    move $t7, $v0
    slt  $t8, $t7, $s0
    beq  $t8, $zero, skip_even
    move $s0, $t7
    move $s1, $s5
    move $s2, $s6
skip_even:
    addi $s4, $s4, 1
    j even_i_loop
end_even_i:

diag_done:
    addi $s3, $s3, 1
    j diag_loop

end_diag:
    move $v0, $s1
    move $v1, $s2

    lw   $ra, 28($sp)
    lw   $s0, 24($sp)
    lw   $s1, 20($sp)
    lw   $s2, 16($sp)
    lw   $s3, 12($sp)
    lw   $s4, 8($sp)
    lw   $s5, 4($sp)
    lw   $s6, 0($sp)
    addi $sp, $sp, 32
    jr   $ra

